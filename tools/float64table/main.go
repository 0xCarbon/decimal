// Command float64table writes float64_table.go:
//   - the 128-bit truncated powers of five that bound Float64's
//     leading-digit enclosure: each entry holds the leading 128 bits of
//     5^q, so 5^q = (M + ε)·2^s with 2^127 ≤ M < 2^128 and 0 ≤ ε < 1,
//     where s = ⌊q·log2 5⌋ − 127;
//   - 5^(13j) and 2^(29j) as exact base-10^9 limbs, so an exact dyadic
//     comparison expands its point with one short multiplication.
//
// Usage: go run ./tools/float64table > float64_table.go
package main

import (
	"bytes"
	"fmt"
	"math/big"
	"os"
)

// The table spans every decimal exponent Float64's bounded path can meet:
// a coefficient of at most 39 digits whose adjusted exponent lies in
// (−326, 309).
const (
	qMin = -363
	qMax = 308
)

func main() {
	os.Stdout.Write(generate())
}

// truncatedPower returns the leading 128 bits of 5^q and whether they are
// all of it (ε = 0).
func truncatedPower(q int) (m *big.Int, exact bool) {
	five := big.NewInt(5)
	if q >= 0 {
		p := new(big.Int).Exp(five, big.NewInt(int64(q)), nil)
		shift := p.BitLen() - 128
		if shift <= 0 {
			return p.Lsh(p, uint(-shift)), true
		}
		m = new(big.Int).Rsh(p, uint(shift))
		return m, new(big.Int).Lsh(m, uint(shift)).Cmp(p) == 0
	}
	d := new(big.Int).Exp(five, big.NewInt(int64(-q)), nil)
	// 2^k/5^−q with k chosen so the quotient has exactly 128 bits.
	k := d.BitLen() + 127
	n := new(big.Int).Lsh(big.NewInt(1), uint(k))
	m, r := new(big.Int).QuoRem(n, d, new(big.Int))
	if m.BitLen() < 128 {
		n.Lsh(n, 1)
		m, r = new(big.Int).QuoRem(n, d, new(big.Int))
	}
	return m, r.Sign() == 0
}

func generate() []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./tools/float64table; DO NOT EDIT.\n\n// SPDX-License-Identifier: Apache-2.0\n\npackage decimal\n\n")
	fmt.Fprintf(&b, "const (\n\tfloat64TableMin = %d\n\tfloat64TableMax = %d\n)\n\n", qMin, qMax)
	b.WriteString("// float64Powers[q−float64TableMin] is {hi, lo} of the leading 128 bits\n// of 5^q (see float64PowerExponent).\n")
	fmt.Fprintf(&b, "var float64Powers = [%d][2]uint64{\n", qMax-qMin+1)
	mask := new(big.Int).SetUint64(^uint64(0))
	for q := qMin; q <= qMax; q++ {
		m, _ := truncatedPower(q)
		lo := new(big.Int).And(m, mask).Uint64()
		hi := new(big.Int).Rsh(m, 64).Uint64()
		fmt.Fprintf(&b, "\t{0x%016X, 0x%016X}, // 5^%d\n", hi, lo, q)
	}
	b.WriteString("}\n")
	writeLimbTable(&b)
	return b.Bytes()
}

// writeLimbTable writes 5^(13j) for j = 0…82 and then 2^(29j) for
// j = 0…35 as little-endian base-10^9 limbs, concatenated, with the start
// of each power in an offsets array whose final entry is the total length.
func writeLimbTable(b *bytes.Buffer) {
	billion := big.NewInt(1_000_000_000)
	var limbs []uint32
	offsets := []int{0}
	for _, family := range []struct{ base, step, last int64 }{{5, 13, 1075 / 13}, {2, 29, 1024 / 29}} {
		for j := int64(0); j <= family.last; j++ {
			p := new(big.Int).Exp(big.NewInt(family.base), big.NewInt(family.step*j), nil)
			for p.Sign() > 0 {
				var r big.Int
				p.QuoRem(p, billion, &r)
				limbs = append(limbs, uint32(r.Uint64()))
			}
			offsets = append(offsets, len(limbs))
		}
	}
	b.WriteString("\n// float64DyadicLimbs holds 5^(13j) for j = 0…82, then 2^(29j) for\n// j = 0…35, as base-10^9 limbs, low limb first. Power i spans\n// [float64DyadicOffsets[i], float64DyadicOffsets[i+1]); the powers of two\n// start at i = float64TwoPowers.\n")
	fmt.Fprintf(b, "const float64TwoPowers = %d\n\n", 1075/13+1)
	fmt.Fprintf(b, "var float64DyadicLimbs = [%d]uint32{", len(limbs))
	for i, limb := range limbs {
		if i%8 == 0 {
			b.WriteString("\n\t")
		} else {
			b.WriteString(" ")
		}
		fmt.Fprintf(b, "%d,", limb)
	}
	b.WriteString("\n}\n\n")
	fmt.Fprintf(b, "var float64DyadicOffsets = [%d]uint16{", len(offsets))
	for i, o := range offsets {
		if i%12 == 0 {
			b.WriteString("\n\t")
		} else {
			b.WriteString(" ")
		}
		fmt.Fprintf(b, "%d,", o)
	}
	b.WriteString("\n}\n")
}
