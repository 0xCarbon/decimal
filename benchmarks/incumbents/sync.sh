# sync.sh refreshes the decimal portfolio copies in this module from
# ../*_test.go (the benchmarks package of the library module). Each copy
# becomes package incumbents; every family that incumbents_test.go
# re-declares has its BenchmarkF<n><Name> renamed to decimalF<n><Name>, so
# the re-declaration runs the decimal rows first and then each incumbent's
# rows in the same binary. Every other benchmark and every test of the
# portfolio is renamed to an unexported function: `go test -bench .` here
# runs only the comparison, and the portfolio's own tests run in the
# library module (go test ./benchmarks). The accuracy preconditions inside
# each benchmark still run before any timing. Run it (or `go generate`) after changing ../*_test.go.
set -eu
cd "$(dirname "$0")"

families=$(sed -n -E 's/^func Benchmark(F[1-8][A-Za-z0-9]*)\(b \*testing\.B\) \{ decimal.*/\1/p' incumbents_test.go)
[ -n "$families" ] || { echo "sync.sh: no re-declared families in incumbents_test.go" >&2; exit 1; }

rm -f decimal_*_test.go
for src in ../*_test.go; do
	name=$(basename "$src")
	dst="decimal_$name"
	{
		printf '// Code generated by sync.sh from benchmarks/%s; DO NOT EDIT.\n\n' "$name"
		sed -E 's/^package benchmarks$/package incumbents/' "$src"
	} > "$dst"
	for f in $families; do
		sed -i.bak -E "s/^func Benchmark${f}\(b \*testing\.B\)/func decimal${f}(b *testing.B)/" "$dst"
	done
	sed -i.bak -E -e 's/^func Benchmark([A-Za-z0-9_]*)\(b \*testing\.B\)/func benchmark\1(b *testing.B)/' \
		-e 's/^func Test([A-Za-z0-9_]*)\(t \*testing\.T\)/func test\1(t *testing.T)/' "$dst"
	rm -f "$dst.bak"
done
gofmt -l . | grep . && { echo "sync.sh: gofmt differences" >&2; exit 1; }
exit 0
